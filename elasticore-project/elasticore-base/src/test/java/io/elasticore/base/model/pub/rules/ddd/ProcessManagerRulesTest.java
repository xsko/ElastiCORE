package io.elasticore.base.model.pub.rules.ddd;

import io.elasticore.base.model.pub.rules.DomainSpec;
import io.elasticore.base.model.pub.rules.EntitySpec;
import io.elasticore.base.model.pub.rules.RuleEngine;
import io.elasticore.base.model.pub.rules.SourceCode;
import io.elasticore.base.util.ConsoleLog;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.util.Arrays;
import java.util.Collections;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * A process manager reacting to its own context's events and to another's
 * (on: [shop:OrderPlaced]).
 */
public class ProcessManagerRulesTest {

    @BeforeEach
    @AfterEach
    public void clearWarnings() {
        ConsoleLog.clearKey("DSL_WARN");
        ConsoleLog.clearKey("DSL_NOTE");
    }

    /** billing, whose own Receipt raises Issued and whose process manager reacts to the given events. */
    private DomainSpec billing(String... on) {
        EntitySpec receipt = new EntitySpec("Receipt")
                .domain("billing", "Billing")
                .meta("root", "")
                .meta("event", "Issued")
                .pkg("entity", "com.acme.billing.domain.model")
                .pkg("event", "com.acme.billing.domain.event")
                .field("receiptId", "long @id");
        return new DomainSpec("billing", "Billing")
                .entity(receipt)
                .pkg("entity", "com.acme.billing.domain.model")
                .pkg("event", "com.acme.billing.domain.event")
                .pkg("service", "com.acme.billing.application")
                .domainService(new DomainSpec.DomainServiceSpec("Receipting", "Bills what shop sells",
                        Collections.<String>emptyList(), Arrays.asList(on)));
    }

    /** The regenerated half: listeners and ports. */
    private String render(DomainSpec d, SourceCode.TemplateSet set) {
        return new RuleEngine().register(new DddDomainServiceRules()).templateSet(set)
                .artifactName("ReceiptingProcessManagerBase").run(d, "processManagerBase").render();
    }

    /** The developer's half, written once. */
    private String renderOwn(DomainSpec d, SourceCode.TemplateSet set) {
        return new RuleEngine().register(new DddDomainServiceRules()).templateSet(set)
                .artifactName("ReceiptingProcessManager").run(d, "processManager").render();
    }

    /**
     * The DSL stays the place a change is made: the base, regenerated, holds the
     * listeners and the ports; the developer's class only writes handle(...).
     */
    @Test
    public void theWiringIsRegeneratedAndOnlyTheStepIsTheDevelopers() {
        DomainSpec d = billing("shop:OrderPlaced")
                .foreignEvent("shop:OrderPlaced", "com.acme.shop.domain.event.OrderPlacedEvent");
        d.entities().get(0).meta("expose", "20");
        DomainSpec withUses = new DomainSpec("billing", "Billing")
                .entity(d.entities().get(0))
                .pkg("entity", "com.acme.billing.domain.model")
                .pkg("event", "com.acme.billing.domain.event")
                .pkg("service", "com.acme.billing.application")
                .pkg("domainRepository", "com.acme.billing.domain.repository")
                .foreignEvent("shop:OrderPlaced", "com.acme.shop.domain.event.OrderPlacedEvent")
                .domainService(new DomainSpec.DomainServiceSpec("Receipting", "Bills what shop sells",
                        Arrays.asList("Receipt"), Arrays.asList("shop:OrderPlaced")));

        String base = render(withUses, SourceCode.TemplateSet.V3);
        assertFalse(base.contains("no longer managed"), "the base is regenerated: " + base);
        assertTrue(base.contains("public abstract class ReceiptingProcessManagerBase {"), base);
        assertTrue(base.contains("@Autowired"), base);
        assertTrue(base.contains("protected ReceiptRepositoryPort receiptRepositoryPort;"), base);
        assertTrue(base.contains("import com.acme.billing.domain.repository.ReceiptRepositoryPort;"), base);
        assertTrue(base.contains("public void on(OrderPlacedEvent event) {"), base);
        assertTrue(base.contains("    handle(event);"), base);
        assertTrue(base.contains("protected abstract void handle(OrderPlacedEvent event);"), base);

        String own = renderOwn(withUses, SourceCode.TemplateSet.V3);
        assertTrue(own.startsWith("// Initially generated by ElastiCORE; no longer managed"), own);
        assertTrue(own.contains("public class ReceiptingProcessManager extends ReceiptingProcessManagerBase {"), own);
        assertTrue(own.contains("@Override"), own);
        assertTrue(own.contains("protected void handle(OrderPlacedEvent event) {"), own);
        assertFalse(own.contains("@TransactionalEventListener"), "the listener is the base's: " + own);
        assertFalse(own.contains("ReceiptRepositoryPort"), "a port is the base's field, not a constructor here: " + own);

        String baseKt = render(withUses, SourceCode.TemplateSet.KOTLIN);
        assertTrue(baseKt.contains("abstract class ReceiptingProcessManagerBase {"), baseKt);
        assertTrue(baseKt.contains("protected lateinit var receiptRepositoryPort: ReceiptRepositoryPort"), baseKt);
        assertTrue(baseKt.contains("open fun on(event: OrderPlacedEvent) {"), baseKt);
        assertTrue(baseKt.contains("protected abstract fun handle(event: OrderPlacedEvent)"), baseKt);
        String ownKt = renderOwn(withUses, SourceCode.TemplateSet.KOTLIN);
        assertTrue(ownKt.contains("open class ReceiptingProcessManager : ReceiptingProcessManagerBase() {"), ownKt);
        assertTrue(ownKt.contains("override fun handle(event: OrderPlacedEvent) {"), ownKt);
    }

    private String renderService(DomainSpec d, String artifact, String target, SourceCode.TemplateSet set) {
        return new RuleEngine().register(new DddDomainServiceRules()).templateSet(set)
                .artifactName(artifact).run(d, target).render();
    }

    /** A domain service: the base holds the ports, in Java and Kotlin; a dropped name is said once. */
    @Test
    public void aDomainServicesPortsAreTheBasesAndItsWarningIsSaidOnce() {
        DomainSpec d = billing();
        d.entities().get(0).meta("expose", "20");
        d.pkg("domainService", "com.acme.billing.domain.service")
         .pkg("domainRepository", "com.acme.billing.domain.repository")
         .domainService(new DomainSpec.DomainServiceSpec("Pricing", "What a receipt costs",
                 Arrays.asList("Receipt", "Nowhere")));

        String base = renderService(d, "PricingDomainServiceBase", "domainServiceBase", SourceCode.TemplateSet.V3);
        assertTrue(base.contains("public abstract class PricingDomainServiceBase {"), base);
        assertTrue(base.contains("protected ReceiptRepositoryPort receiptRepositoryPort;"), base);
        assertFalse(base.contains("Nowhere"), base);
        String own = renderService(d, "PricingDomainService", "domainService", SourceCode.TemplateSet.V3);
        assertTrue(own.contains("public class PricingDomainService extends PricingDomainServiceBase {"), own);
        assertFalse(own.contains("RepositoryPort"), own);
        String baseKt = renderService(d, "PricingDomainServiceBase", "domainServiceBase", SourceCode.TemplateSet.KOTLIN);
        assertTrue(baseKt.contains("protected lateinit var receiptRepositoryPort: ReceiptRepositoryPort"), baseKt);
        String ownKt = renderService(d, "PricingDomainService", "domainService", SourceCode.TemplateSet.KOTLIN);
        assertTrue(ownKt.contains("open class PricingDomainService : PricingDomainServiceBase() {"), ownKt);

        assertEquals(2, ConsoleLog.countByPrefix("DSL_WARN", "[billing] domainService Pricing: 'Nowhere' is not an entity"),
                "once per base render (Java, Kotlin) - never from the developer's file");
    }

    /** Nothing resolved and nothing used: an empty base, and nothing the transaction listener needs. */
    @Test
    public void anEmptyProcessManagerIsAnEmptyBase() {
        String base = render(billing("Nothing"), SourceCode.TemplateSet.V3);
        assertTrue(base.contains("public abstract class ReceiptingProcessManagerBase {"), base);
        assertFalse(base.contains("abstract void handle"), base);
        assertFalse(base.contains("import org.springframework"), base);
        String own = renderOwn(billing("Nothing"), SourceCode.TemplateSet.V3);
        assertFalse(own.contains("handle("), own);
    }

    /** Both files resolve the events; only the base's rule says what it left out. */
    @Test
    public void whatIsLeftOutIsSaidOnce() {
        DomainSpec d = billing("Nothing");
        render(d, SourceCode.TemplateSet.V3);
        renderOwn(d, SourceCode.TemplateSet.V3);
        assertEquals(1, ConsoleLog.countByPrefix("DSL_WARN",
                "[billing] processManager Receipting: no root declares the event Nothing"));
    }

    @Test
    public void anotherContextsEventIsImportedFromItsPackage() {
        DomainSpec d = billing("shop:OrderPlaced", "ReceiptIssued")
                .foreignEvent("shop:OrderPlaced", "com.acme.shop.domain.event.OrderPlacedEvent");

        String java = render(d, SourceCode.TemplateSet.V3);
        assertTrue(java.contains("import com.acme.shop.domain.event.OrderPlacedEvent;"), java);
        assertTrue(java.contains("import com.acme.billing.domain.event.ReceiptIssuedEvent;"), java);
        assertTrue(java.contains("public void on(OrderPlacedEvent event) {"), java);
        assertTrue(java.contains("public void on(ReceiptIssuedEvent event) {"), java);
        assertTrue(java.contains("@TransactionalEventListener(phase = TransactionPhase.AFTER_COMMIT, fallbackExecution = true)"), java);

        String kotlin = render(d, SourceCode.TemplateSet.KOTLIN);
        assertTrue(kotlin.contains("import com.acme.shop.domain.event.OrderPlacedEvent"), kotlin);
        assertTrue(kotlin.contains("open fun on(event: OrderPlacedEvent) {"), kotlin);
        assertEquals(0, ConsoleLog.countByPrefix("DSL_WARN", "[billing]"));
    }

    /** shop's ReceiptIssuedEvent and billing's own share a simple name: the foreign one is written in full. */
    @Test
    public void aClassNameTakenHereIsWrittenInFull() {
        DomainSpec d = billing("ReceiptIssued", "shop:ReceiptIssued")
                .foreignEvent("shop:ReceiptIssued", "com.acme.shop.domain.event.ReceiptIssuedEvent");

        String java = render(d, SourceCode.TemplateSet.V3);
        assertTrue(java.contains("import com.acme.billing.domain.event.ReceiptIssuedEvent;"), java);
        assertFalse(java.contains("import com.acme.shop.domain.event.ReceiptIssuedEvent;"), java);
        assertTrue(java.contains("public void on(ReceiptIssuedEvent event) {"), java);
        assertTrue(java.contains("public void on(com.acme.shop.domain.event.ReceiptIssuedEvent event) {"), java);
    }

    /** billing raises ReceiptIssued but does not listen to it: shop's event of that name is simply imported. */
    @Test
    public void aLocalEventNotListenedToTakesNoName() {
        String java = render(billing("shop:ReceiptIssued")
                .foreignEvent("shop:ReceiptIssued", "com.acme.shop.domain.event.ReceiptIssuedEvent"), SourceCode.TemplateSet.V3);
        assertTrue(java.contains("import com.acme.shop.domain.event.ReceiptIssuedEvent;"), java);
        assertTrue(java.contains("public void on(ReceiptIssuedEvent event) {"), java);
    }

    @Test
    public void anEventNamedTwiceGetsOneHandler() {
        String java = render(billing("shop:OrderPlaced", "shop:OrderPlacedEvent")
                .foreignEvent("shop:OrderPlaced", "com.acme.shop.domain.event.OrderPlacedEvent")
                .foreignEvent("shop:OrderPlacedEvent", "com.acme.shop.domain.event.OrderPlacedEvent"), SourceCode.TemplateSet.V3);
        assertEquals(java.indexOf("public void on("), java.lastIndexOf("public void on("), java);
        // A decision said, not a fault of the DSL: a note, which a validation does not count.
        assertEquals(1, ConsoleLog.countByPrefix("DSL_NOTE",
                "[billing] processManager Receipting: shop:OrderPlacedEvent is named twice in 'on'; it gets one handler."));
        assertEquals(0, ConsoleLog.countByPrefix("DSL_WARN", "[billing] processManager Receipting: shop:OrderPlacedEvent"));
    }

    @Test
    public void theGeneratorsReasonIsSaidWhenItHasOne() {
        String java = render(billing("catalog:BookPublished")
                .foreignEventProblem("catalog:BookPublished", "catalog declares it, but its rules generate no event classes"),
                SourceCode.TemplateSet.V3);
        assertFalse(java.contains("public void on("), java);
        assertEquals(1, ConsoleLog.countByPrefix("DSL_WARN",
                "[billing] processManager Receipting: catalog:BookPublished - catalog declares it, but its rules generate no event classes."));
    }

    @Test
    public void anEventThatCannotBeFoundIsSaidAndLeftOut() {
        DomainSpec d = billing("shop:OrderShiped", "OrderPlaced", "Nothing")
                .eventElsewhere("OrderPlaced", "shop");

        String java = render(d, SourceCode.TemplateSet.V3);
        assertFalse(java.contains("public void on("), java);
        assertEquals(1, ConsoleLog.countByPrefix("DSL_WARN",
                "[billing] processManager Receipting: shop declares no event OrderShiped - name another context's event as"
                        + " context:RootEvent (shop:OrderPlaced), as that root's @event declares it."));
        assertEquals(1, ConsoleLog.countByPrefix("DSL_WARN",
                "[billing] processManager Receipting: OrderPlaced is an event of shop - write shop:OrderPlaced"
                        + " (and list shop in config.context.uses)."));
        assertEquals(1, ConsoleLog.countByPrefix("DSL_WARN",
                "[billing] processManager Receipting: no root declares the event Nothing - add it to that root's @event."));
    }
}
