    @Test
    public void theEntityIsADocumentAndNamesNothingOfJpa() throws Exception {
        File project = project(MODEL, "mongo");
        run(project, 0);

        String order = read(project, "PurchaseOrder.java");
        assertTrue(order.contains("@Document(collection = \"purchase_order\")"), order);
        assertTrue(order.contains("@Id\n\tprivate Long orderId;"), order);
        // A named column is the field's name in the document; a derived one is the property's.
        assertTrue(order.contains("@Field(value = \"order_number\")\n\tprivate String orderNo;"), order);
        assertTrue(order.contains("\tprivate LocalDateTime deliveredAt;"), order);
        assertFalse(order.contains("delivered_at"), order);
        // An enum with @db is stored by its code, through its JPA converter.
        assertTrue(
                order.contains("@ValueConverter(value = io.elasticore.springboot3.mongo.AttributeValueConverter.class)"
                        + "\n\tprivate OrderStatus status;"),
                order);
        assertTrue(
                order.contains("@Field(targetType = org.springframework.data.mongodb.core.mapping.FieldType.DECIMAL128)"
                        + "\n\tprivate BigDecimal total;"),
                order);
        // Another collection's document by its id; the members in the document.
        assertTrue(order.contains("@DocumentReference(lazy = true)\n\tprivate Customer customer;"), order);
        assertTrue(order.contains("\n\tprivate List<OrderLine> items;"), order);
        assertTrue(order.contains("import org.springframework.data.annotation.Version;"), order);
        assertTrue(order.contains("@Version\n\tprivate Long version;"), order);

        String line = read(project, "OrderLine.java");
        assertFalse(line.contains("@Document"), line);
        assertTrue(line.contains("@Transient\n\tprivate PurchaseOrder order;"), line);

        String customer = read(project, "Customer.java");
        assertTrue(customer.contains("@Indexed(unique = true, sparse = true)\n\tprivate String email;"), customer);
        assertTrue(customer.contains("@CreatedDate\n\tprivate LocalDateTime joinedAt;"), customer);
        assertTrue(customer.contains("\n\tprivate Address address;"), customer);
        assertFalse(read(project, "Address.java").contains("@Document"));
        for (String name : new String[] {
            "PurchaseOrder.java",
            "OrderLine.java",
            "Customer.java",
            "Address.java",
            "PurchaseOrderRepository.java",
            "CustomerRepository.java",
            "PurchaseOrderCoreService.java",
            "CustomerCoreService.java",
            "DgshopMapper.java",
            "DgshopRepositoryHelper.java"
        }) {
            String text = read(project, name);
            assertFalse(text.contains("jakarta.persistence"), name + "\n" + text);
            assertFalse(text.contains("org.hibernate"), name + "\n" + text);
            assertFalse(text.contains("EntityManager"), name + "\n" + text);
        }
        assertNull(find(project, "Q.java"), "Q is JPA's metadata");
        assertNull(find(project, "OrderLineRepository.java"), "a member is kept in its order");
        assertNull(find(project, "OrderLineCoreService.java"), "a member is kept in its order");
    }

    @Test
    public void theRepositoryIsAMongoRepositoryWithTheSearch() throws Exception {
        File project = project(MODEL, "mongo");
        run(project, 0);
        String repo = read(project, "PurchaseOrderRepository.java");
        assertTrue(
                repo.contains(
                        "public interface PurchaseOrderRepository extends MongoRepository<PurchaseOrder, Long> {"),
                repo);
        assertTrue(
                repo.contains("and.add(Criteria.where(\"status\").is("
                        + "io.elasticore.springboot3.mongo.AttributeValueConverter.stored(s.getStatus())));"),
                repo);
        // A reference is searched by a stand-in of the document it points at.
        assertTrue(
                repo.contains("and.add(Criteria.where(\"customer\").is(customerRef(s.getCustomerCustomerId())));"),
                repo);
        assertTrue(repo.contains("ref.setCustomerId(id);"), repo);
        assertTrue(
                repo.contains(
                        "if (s.getAmountFrom() != null) and.add(Criteria.where(\"amount\").gte(s.getAmountFrom()));"),
                repo);
        assertTrue(
                repo.contains("if (s.getAmountTo() != null) and.add(Criteria.where(\"amount\").lte(s.getAmountTo()));"),
                repo);
        assertTrue(
                repo.contains(".regex(io.elasticore.springboot3.mongo.MongoText.match(s.getMemo().trim(), true, true,"),
                repo);
        assertTrue(
                repo.contains("Boolean.TRUE.equals(s.getDeliveredAtEmpty()) ? Criteria.where(\"deliveredAt\").is(null)"
                        + " : Criteria.where(\"deliveredAt\").ne(null)"),
                repo);
        // The owner's documents only, when read is the owner's.
        assertTrue(repo.contains("if (owner != null) and.add(Criteria.where(\"ownerId\").is(owner));"), repo);
        assertTrue(repo.contains("m.put(\"customer.customerId\", \"customer\");"), repo);
        assertTrue(repo.contains("throw new BadRequestException(\"PurchaseOrder cannot be sorted by '\""), repo);
        assertTrue(repo.contains("static boolean hasCondition("), repo);

        // @deleted: every search leaves the deleted ones out.
        String customers = read(project, "CustomerRepository.java");
        assertTrue(customers.contains("and.add(Criteria.where(\"retiredAt\").is(null));"), customers);
    }

    @Test
    public void theServiceKeepsTheJpaSignatures() throws Exception {
        File project = project(MODEL, "mongo");
        run(project, 0);
        String service = read(project, "PurchaseOrderCoreService.java");
        for (String signature : new String[] {
            "public Optional<PurchaseOrderDTO> findById(Long orderId) {",
            "public Page<PurchaseOrderDTO> findBySearch(PurchaseOrderSrchDTO searchDTO) {",
            "public List<PurchaseOrderDTO> listBySearch(PurchaseOrderSrchDTO searchDTO) {",
            "public PurchaseOrderDTO findFirstBySearch(PurchaseOrderSrchDTO searchDTO) {",
            "public long countBySearch(PurchaseOrderSrchDTO searchDTO) {",
            "public PurchaseOrderDTO save(PurchaseOrderDTO dto) {",
            "public PurchaseOrderDTO update(PurchaseOrderDTO dto) {",
            "public void batchUpdate(List<PurchaseOrderDTO> dtoList) {",
            "public List<Boolean> delete(List<PurchaseOrderKeyDTO> dtoList) {",
            "public boolean deleteById(Long orderId) {",
            "public long delete(PurchaseOrderSrchDTO searchDTO) {",
            "public int updateBySpecification(PurchaseOrderDTO dto, PurchaseOrderSrchDTO srchDTO) {"
        }) {
            assertTrue(service.contains(signature), signature + "\n" + service);
        }
        // The key from the sequences, the members' keys too.
        assertTrue(
                service.contains("entity.setOrderId(io.elasticore.springboot3.mongo.MongoSequences.next(mongo,"
                        + " \"purchase_order\"));"),
                service);
        assertTrue(
                service.contains("if (m.getLineId() == null) m.setLineId(io.elasticore.springboot3.mongo.MongoSequences"
                        + ".next(mongo, \"order_line\"));"),
                service);
        assertTrue(
                service.contains("long total = mongo.count(query(searchDTO, owner), PurchaseOrder.class);"), service);
        assertTrue(service.contains("query.skip(pageable.getOffset()).limit(pageable.getPageSize());"), service);
        assertTrue(service.contains("VersionCheck.check(dto, \"version\""), service);
        // The access checks narrow a search to the owner's documents, and refuse with the runtime's 404.
        assertTrue(service.contains("private Object ownedOnly()"), service);
        assertTrue(service.contains("throw new NotFoundException(\"PurchaseOrder not found\");"), service);
        assertFalse(service.contains("@Transactional"), service);
        assertFalse(service.contains("Specification<"), service);

        // @deleted: a delete writes the time, a read leaves it out; the service stamps @CreatedDate.
        String customer = read(project, "CustomerCoreService.java");
        assertTrue(customer.contains("e.setRetiredAt(java.time.LocalDateTime.now());"), customer);
        assertTrue(customer.contains("findById(customerId).filter(e -> e.getRetiredAt() == null)"), customer);
        assertTrue(
                customer.contains(
                        "if (entity.getJoinedAt() == null) entity.setJoinedAt(java.time.LocalDateTime.now());"),
                customer);

        // The members arrive with their order, and the mapper writes them onto it.
        String mapper = read(project, "DgshopMapper.java");
        assertTrue(
                mapper.contains("java.util.List<OrderLine> members = new java.util.ArrayList<OrderLine>();"), mapper);
        assertFalse(mapper.contains("toSpec"), mapper);
        assertTrue(read(project, "DgshopRepositoryHelper.java").contains("Holds a domain's MongoDB repositories"));
    }

