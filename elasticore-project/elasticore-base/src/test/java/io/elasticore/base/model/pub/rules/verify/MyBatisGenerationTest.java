/**
 * A domain whose env.yml says mode: mybatis, generated by elcore3: what is
 * written, what is left out, and what is refused. That the code compiles and
 * answers over HTTP is shown by elasticore-template-mybatis.
 */
public class MyBatisGenerationTest {

    private static final String[] KEYS = {"elasticore.base.path", "elasticore.architecture",
            "elasticore.language", "elasticore.rules.force", "elasticore.rules.v2", "elasticore.rules.v3",
            "elasticore.rules.ts", "elasticore.rules.kt", "elasticore.publisher.rules.add", "elasticore.rules.list"};

    private static final String MODEL = String.join("\n",
            "enumeration:",
            "  OrderStatus:",
            "    meta: enum @db(code) @json(code)",
            "    fields:",
            "      code: string(1) @code",
            "      name: string(20)",
            "    enum:",
            "      NEW: N,New",
            "      PAID: P,Paid",
            "",
            "entity:",
            "  Customer:",
            "    meta: entity @expose(20) @access(*=public)",
            "    fields:",
            "      customerId: long @id @sequence",
            "      name: string(50)! @search(like)",
            "",
            "  PurchaseOrder:",
            "    meta: entity @expose(20) @owner(ownerId) @access(read=owner, *=public)",
            "    fields:",
            "      orderId: long @id @sequence",
            "      orderNo: string(20)! @search(eq)",
            "      status: OrderStatus! @search(eq)",
            "      amount: long! @search(between)",
            "      customer: Customer! @ManyToOne @search(eq)",
            "      ownerId: long",
            "      createdAt: datetime @jpa:CreatedDate",
            "      version: long @jpa:Version",
            "");

    private final List<File> projects = new ArrayList<File>();
    private final String[] saved = save();

    @AfterEach
    void clean() throws IOException {
        for (int i = 0; i < KEYS.length; i++) {
            if (saved[i] == null) System.clearProperty(KEYS[i]);
            else System.setProperty(KEYS[i], saved[i]);
        }
        for (File p : projects) delete(p.toPath());
    }

    @Test
    public void theEntityAndTheServiceNameNothingOfJpa() throws Exception {
        File project = project(MODEL, "mybatis");
        String log = run(project, 0);
        assertTrue(log.contains("mode: mybatis"), log);

        String entity = read(project, "PurchaseOrder.java");
        assertFalse(entity.contains("jakarta.persistence"), entity);
        assertFalse(entity.contains("org.hibernate"), entity);
        assertFalse(entity.contains("@Version"), entity);
        assertTrue(entity.contains("private Customer customer;"), entity);

        String service = read(project, "PurchaseOrderCoreService.java");
        assertFalse(service.contains("Specification<"), service);
        assertFalse(service.contains("EntityManager"), service);
        assertTrue(service.contains("helper.getPurchaseOrder().countBySearch(searchDTO, owner)"), service);
        // The owner's rows only, through the mapper.
        assertTrue(service.contains("private Object ownedOnly()"), service);
        // What JPA's auditing and version did, the service does.
        assertTrue(service.contains("if (entity.getCreatedAt() == null) entity.setCreatedAt(java.time.LocalDateTime.now());"), service);
        assertTrue(service.contains("VersionCheck.check(dto, \"version\""), service);

        String mapper = read(project, "DgshopMapper.java");
        assertFalse(mapper.contains("EntityManager"), mapper);
        assertFalse(mapper.contains("Specification"), mapper);

        assertNull(find(project, "Q.java"), "Q is JPA's metadata");
        assertNotNull(find(project, "PurchaseOrderController.java"));
    }

    @Test
    public void theXmlIsAMapperMyBatisReads() throws Exception {
        File project = project(MODEL, "mybatis");
        run(project, 0);
        Path xml = findResource(project, "PurchaseOrderRepository.xml");
        assertNotNull(xml);
        String text = new String(Files.readAllBytes(xml), StandardCharsets.UTF_8);
        // The stamp is a comment, so the file is still XML.
        assertTrue(text.startsWith("<!-- //ecd:"), text);
        DocumentBuilderFactory f = DocumentBuilderFactory.newInstance();
        f.setValidating(false);
        f.setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false);
        DocumentBuilder b = f.newDocumentBuilder();
        Document doc = b.parse(xml.toFile());
        assertEquals("io.acme.dgshop.repository.PurchaseOrderRepository",
                doc.getDocumentElement().getAttribute("namespace"));

        assertTrue(text.contains("LEFT JOIN customer j1 ON j1.customer_id = t.customer_customer_id"), text);
        assertTrue(text.contains("AND t.amount &gt;= #{s.amountFrom,jdbcType=BIGINT}"), text);
        assertTrue(text.contains("AND t.customer_customer_id = #{s.customerCustomerId,jdbcType=BIGINT}"), text);
        assertTrue(text.contains("typeHandler=io.elasticore.springboot3.mybatis.ConvertedEnumTypeHandler"), text);
        assertTrue(text.contains("<if test=\"owner != null\">AND t.owner_id = #{owner}</if>"), text);
        assertTrue(text.contains("version = COALESCE(version, 0) + 1"), text);
        assertTrue(text.contains("useGeneratedKeys=\"true\" keyProperty=\"orderId\" keyColumn=\"order_id\""), text);

        String repo = read(project, "PurchaseOrderRepository.java");
        assertTrue(repo.contains("m.put(\"customer.name\", \"j1.name\");"), repo);
        assertTrue(repo.contains("@Mapper"), repo);
    }

    @Test
    public void theSchemaCreatesTheTablesAndTheirKeys() throws Exception {
        File project = project(MODEL, "mybatis");
        run(project, 0);
        File sql = new File(project, "src/main/resources/db/dgshop-schema.sql");
        assertTrue(sql.isFile());
        String text = new String(Files.readAllBytes(sql.toPath()), StandardCharsets.UTF_8);
        assertTrue(text.startsWith("-- //ecd:"), text);
        assertTrue(text.contains("customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL"), text);
        assertTrue(text.contains("status VARCHAR(1) NOT NULL"), text);
        assertTrue(text.contains("ALTER TABLE purchase_order ADD CONSTRAINT fk_purchase_order_customer"
                + " FOREIGN KEY (customer_customer_id) REFERENCES customer (customer_id);"), text);
    }

    @Test
    public void aCollectionRelationIsRefusedNotDropped() throws Exception {
        File project = project(String.join("\n",
                "entity:",
                "  Basket:",
                "    meta: entity @expose(20)",
                "    fields:",
                "      basketId: long @id @sequence",
                "      items: List<Item> @OneToMany",
                "  Item:",
                "    meta: entity @expose(20)",
                "    fields:",
                "      itemId: long @id @sequence",
                "      basket: Basket @ManyToOne",
                ""), "mybatis");
        String log = run(project, 1);
        assertTrue(log.contains("Basket: mode: mybatis does not write items: a collection relation"), log);
        assertNull(find(project, "Basket.java"), log);
    }

    @Test
    public void aHexagonOverMyBatisIsRefused() throws Exception {
        File project = project(MODEL, "mybatis");
        System.setProperty("elasticore.architecture", "hexagonal");
        String log = run(project, 1);
        assertTrue(log.contains("MyBatis code is layered"), log);
        assertNull(find(project, "PurchaseOrder.java"), log);
    }

    @Test
    public void aJpaDomainBesideItIsUnchanged() throws Exception {
        File project = project(MODEL, "jpa");
        run(project, 0);
        String entity = read(project, "PurchaseOrder.java");
        assertTrue(entity.contains("@Entity"), entity);
        assertNull(findResource(project, "PurchaseOrderRepository.xml"));
        assertNotNull(find(project, "Q.java"));
    }

    // ---- helpers -----------------------------------------------------------------------

    private String run(File project, int expected) throws Exception {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        PrintStream out = System.out;
        System.setOut(new PrintStream(bytes, true, "UTF-8"));
        int code;
        try {
            System.setProperty("elasticore.base.path", project.getAbsolutePath());
            System.setProperty("elasticore.rules.force", "true");
            code = RulesGenRunner.run(new String[0]);
        } finally {
            System.setOut(out);
        }
        String log = new String(bytes.toByteArray(), StandardCharsets.UTF_8);
        out.print(log);
        assertEquals(expected, code, log);
        return log;
    }

    private File project(String model, String mode) throws IOException {
        File dir = Files.createTempDirectory("elcore-mybatis").toFile();
        projects.add(dir);
        File blueprint = new File(dir, "src/main/resources/blueprint/dgshop");
        assertTrue(new File(blueprint, "model").mkdirs());
        String env = String.join("\n",
                "elasticore:",
                "  enable: true",
                "  config:",
                "    domainName: dgshop",
                "    framework: springboot",
                "    mode: " + mode,
                "    j2ee: jakarta",
                "  namespace:",
                "    base: io.acme.dgshop",
                "    entity: io.acme.dgshop.entity",
                "    repository: io.acme.dgshop.repository",
                "");
        Files.write(new File(blueprint, "env.yml").toPath(), env.getBytes(StandardCharsets.UTF_8));
        Files.write(new File(blueprint, "model/model.yml").toPath(), model.getBytes(StandardCharsets.UTF_8));
        return dir;
    }

    private static String read(File project, String name) throws IOException {
        Path p = find(project, name);
        assertNotNull(p, name + " was not written");
        return new String(Files.readAllBytes(p), StandardCharsets.UTF_8);
    }

    private static Path find(File project, String name) throws IOException {
        return findUnder(new File(project, "src/main/java"), name);
    }

    private static Path findResource(File project, String name) throws IOException {
        return findUnder(new File(project, "src/main/resources"), name);
    }

    private static Path findUnder(File root, String name) throws IOException {
        if (!root.isDirectory()) return null;
        try (Stream<Path> all = Files.walk(root.toPath())) {
            return all.filter(p -> p.getFileName().toString().equals(name)).findFirst().orElse(null);
        }
    }

    private static String[] save() {
        String[] s = new String[KEYS.length];
        for (int i = 0; i < KEYS.length; i++) s[i] = System.getProperty(KEYS[i]);
        return s;
    }

    private static void delete(Path root) throws IOException {
        if (!Files.exists(root)) return;
        try (Stream<Path> all = Files.walk(root)) {
            List<Path> paths = new ArrayList<Path>();
            all.forEach(paths::add);
            for (int i = paths.size() - 1; i >= 0; i--) Files.deleteIfExists(paths.get(i));
        }
    }
}
