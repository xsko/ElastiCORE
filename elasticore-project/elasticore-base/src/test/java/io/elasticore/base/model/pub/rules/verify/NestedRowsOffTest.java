package io.elasticore.base.model.pub.rules.verify;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.File;
import java.io.IOException;
import java.net.URL;
import java.net.URLClassLoader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.TreeMap;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.Assumptions;
import org.junit.jupiter.api.Test;

/**
 * config: nestedRows is off by default on 3.0 (issue 321): a project that does not say nestedRows: readers generates
 * what it did - the MANAGER-only product left out of the DTO, with the warning, which names the switch, no
 * withoutCarriedRows, no product in the TypeScript type. Not saying it and saying nestedRows: public write the same
 * bytes. With ELASTICORE_BASELINE_JAR naming an elasticore-base jar built before the switch, every reading is
 * generated by both and compared byte for byte; without it that comparison is skipped.
 */
public class NestedRowsOffTest {

    private static final List<File> projects = new ArrayList<File>();

    /** architecture, language, mode, model. */
    private static final String[][] READINGS = {
        {"layered", "java", "jpa", CarriedRowTest.MODEL + CarriedRowTest.MEMBER},
        {"layered", "kotlin", "jpa", CarriedRowTest.MODEL + CarriedRowTest.MEMBER},
        {"hexagonal", "java", "jpa", CarriedRowTest.MODEL + CarriedRowTest.CLAIM},
        {"hexagonal", "kotlin", "jpa", CarriedRowTest.MODEL + CarriedRowTest.CLAIM},
        {"ddd", "java", "jpa", CarriedRowTest.MODEL + CarriedRowTest.CLAIM},
        {"layered", "java", "mybatis", CarriedRowTest.MODEL + CarriedRowTest.MEMBER},
        {"hexagonal", "java", "mybatis", CarriedRowTest.MODEL + CarriedRowTest.CLAIM},
        {"layered", "java", "mongo", CarriedRowTest.MODEL + CarriedRowTest.MEMBER},
        {"layered", "kotlin", "mongo", CarriedRowTest.MODEL},
        {"layered", "typescript", "jpa", CarriedRowTest.MODEL},
    };

    @AfterAll
    static void cleanUp() throws Exception {
        java.lang.reflect.Field tmp =
                io.elasticore.base.model.core.BaseECoreModelContext.class.getDeclaredField("tmpCtx");
        tmp.setAccessible(true);
        tmp.set(null, null);
        SpecFactory.valueObjectsInDto(false);
        SpecFactory.rootsSplitByDefault(false);
        SpecFactory.commandOnlyRoots(false);
        SpecFactory.referenceRequiredByKey(false);
        for (File project : projects) CarriedRowTest.delete(project);
    }

    private static File project(String name, String mode, String model, String nestedRows) throws IOException {
        File project = Files.createTempDirectory(name).toFile();
        projects.add(project);
        CarriedRowTest.blueprint(project, mode, model, nestedRows);
        return project;
    }

    private static String current(File project, String architecture, String language) throws Exception {
        return CarriedRowTest.generate(project, architecture, language, () -> RulesGenRunner.run(new String[0]));
    }

    /** Off: today's output, and the warning says where the switch is. */
    @Test
    public void offLeavesTheRowOutAndSaysWhereTheSwitchIs() throws Exception {
        File java = project("elcore-off-j", "jpa", CarriedRowTest.MODEL + CarriedRowTest.MEMBER, null);
        String log = current(java, "layered", "java");
        String dto = only(java, "CrCoverageDTO.java");
        assertFalse(dto.contains("CrProductDTO"), dto);
        assertFalse(only(java, "CrCoverageCoreService.java").contains("withoutCarriedRows"));
        assertFalse(only(java, "CrMemberCoreService.java").contains("withoutCarriedRows"));
        assertFalse(only(java, "CrshopMapper.java").contains("to::setProduct,"));
        assertTrue(
                log.contains("CrCoverage.product is left out: CrProductDTO is read under @access(read=MANAGER)")
                        && log.contains("config: nestedRows: readers in env.yml carries it."),
                log);
        // A row no reader of the holder may see says nothing of the switch: CrNote is read at user.
        int note = log.indexOf("CrNote.product is left out");
        assertTrue(note >= 0, log);
        assertFalse(log.substring(note, log.indexOf('\n', note)).contains("nestedRows"), log);

        File ts = project("elcore-off-ts", "jpa", CarriedRowTest.MODEL, null);
        current(ts, "layered", "typescript");
        assertFalse(tree(ts).toString().contains("product?: CrProductDTO"));
    }

    /** nestedRows: public says what not saying it says. */
    @Test
    public void publicIsTheDefault() throws Exception {
        for (String[] r : READINGS) {
            File unset = project("elcore-off-u", r[2], r[3], null);
            File said = project("elcore-off-p", r[2], r[3], "public");
            current(unset, r[0], r[1]);
            current(said, r[0], r[1]);
            assertSame(tree(unset), tree(said), String.join("/", r) + ": nestedRows: public differs from unset");
        }
    }

    /** Off, every reading is the bytes the generator wrote before the switch. */
    @Test
    public void offIsTheOutputOfBefore() throws Exception {
        String jar = System.getenv("ELASTICORE_BASELINE_JAR");
        Assumptions.assumeTrue(jar != null && new File(jar).isFile(), "ELASTICORE_BASELINE_JAR names no jar");
        for (String[] r : READINGS) {
            File now = project("elcore-off-n", r[2], r[3], null);
            File before = project("elcore-off-b", r[2], r[3], null);
            current(now, r[0], r[1]);
            CarriedRowTest.generate(before, r[0], r[1], () -> baseline(new File(jar)));
            TreeMap<String, String> a = tree(now);
            assertTrue(a.size() > 10, String.join("/", r) + ": " + a.keySet());
            assertSame(a, tree(before), String.join("/", r) + ": differs from the baseline");
        }
    }

    /** RulesGenRunner.run of the baseline jar, in a class loader of its own: the jar first, the libraries after. */
    private static int baseline(File jar) throws Exception {
        List<URL> urls = new ArrayList<URL>();
        urls.add(jar.toURI().toURL());
        for (String entry : System.getProperty("java.class.path").split(File.pathSeparator)) {
            String normalized = entry.replace('\\', '/');
            if (normalized.contains("/elasticore-base/build/")) continue;
            urls.add(new File(entry).toURI().toURL());
        }
        ClassLoader parent = ClassLoader.getSystemClassLoader().getParent();
        Thread thread = Thread.currentThread();
        ClassLoader context = thread.getContextClassLoader();
        try (URLClassLoader loader = new URLClassLoader(urls.toArray(new URL[0]), parent)) {
            thread.setContextClassLoader(loader);
            Class<?> runner = loader.loadClass("io.elasticore.base.model.pub.rules.verify.RulesGenRunner");
            java.lang.reflect.Method run = runner.getDeclaredMethod("run", String[].class);
            run.setAccessible(true);
            return (Integer) run.invoke(null, (Object) new String[0]);
        } finally {
            thread.setContextClassLoader(context);
        }
    }

    /** Every generated file, by its path in the project, outside the blueprint and the merge cache. */
    private static TreeMap<String, String> tree(File project) throws IOException {
        TreeMap<String, String> out = new TreeMap<String, String>();
        Path root = project.toPath();
        try (java.util.stream.Stream<Path> all = Files.walk(root)) {
            for (Path p : all.toArray(Path[]::new)) {
                if (!Files.isRegularFile(p)) continue;
                String rel = root.relativize(p).toString().replace('\\', '/');
                // The guides copied into the blueprint are documentation, which the switch adds to.
                // build/elasticore/ts-client.model is a digest of the blueprint (env.yml, the guides), not a source.
                if (rel.startsWith(".elasticore/")
                        || rel.equals("build/elasticore/ts-client.model")
                        || rel.contains("/blueprint/crshop/")
                        || (rel.contains("/blueprint/") && rel.endsWith(".md"))) continue;
                out.put(rel, new String(Files.readAllBytes(p), StandardCharsets.UTF_8));
            }
        }
        return out;
    }

    private static void assertSame(TreeMap<String, String> a, TreeMap<String, String> b, String what) {
        assertEquals(a.keySet(), b.keySet(), what);
        for (String k : a.keySet()) assertEquals(a.get(k), b.get(k), what + ": " + k);
    }

    private static String only(File project, String name) throws IOException {
        List<String> hits = new ArrayList<String>();
        for (java.util.Map.Entry<String, String> e : tree(project).entrySet()) {
            if (e.getKey().endsWith("/" + name)) hits.add(e.getValue());
        }
        assertEquals(1, hits.size(), name);
        return hits.get(0);
    }
}
