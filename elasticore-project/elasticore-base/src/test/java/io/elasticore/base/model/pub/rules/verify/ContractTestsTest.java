    @Test
    public void aPatternGivesAValueThatMatchesAndOneThatDoesNot() {
        assertEquals("AA000", PatternSample.matching("[A-Z]{2}[0-9]{3}", 0, 8));
        assertEquals("!", PatternSample.notMatching("[A-Z]{2}[0-9]{3}", "AA000"));
        String phone = PatternSample.matching("^\\d{3}-\\d{3,4}-\\d{4}$", 0, 20);
        assertNotNull(phone);
        assertTrue(phone.matches("\\d{3}-\\d{3,4}-\\d{4}"), phone);
        // A length the field asks for is met by taking more of an open quantifier.
        String word = PatternSample.matching("[a-z]+", 4, 10);
        assertNotNull(word);
        assertTrue(word.length() >= 4 && word.length() <= 10, word);
        assertEquals("a", PatternSample.matching("(a|b)c?", 0, 5));
        // No sample where the expression asks what the reader does not read, or nothing fits.
        assertEquals(null, PatternSample.matching("(?=x)x", 0, 5));
        assertEquals(null, PatternSample.matching("[a-z]{10}", 0, 5));
        assertEquals("!", PatternSample.notMatching("[0-9]*", null));
    }

