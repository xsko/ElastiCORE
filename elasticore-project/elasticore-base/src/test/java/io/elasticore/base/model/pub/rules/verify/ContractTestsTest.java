        assertTrue(
                t.contains(
                        "assertCreated(post(SHIPMENT, withValue(newShipment(), \"code\", \"AA000\")));\n"
                                + "        assertFieldError(post(SHIPMENT, withValue(newShipment(), \"code\", \"!\")), \"code\", \"Pattern\");"),
                t);
