    private String run(File project, String architecture, String language) throws Exception {
        ByteArrayOutputStream bytes = new ByteArrayOutputStream();
        PrintStream out = System.out;
        System.setOut(new PrintStream(bytes, true, "UTF-8"));
        int code;
        try {
            System.setProperty("elasticore.base.path", project.getAbsolutePath());
            System.setProperty("elasticore.rules.force", "true");
            System.setProperty("elasticore.architecture", architecture);
            System.setProperty("elasticore.language", language);
            code = RulesGenRunner.run(new String[0]);
        } finally {
            System.setOut(out);
        }
        String log = new String(bytes.toByteArray(), StandardCharsets.UTF_8);
        out.print(log);
        assertEquals(0, code, log);
        return log;
    }

    private static String read(File project, String path) throws IOException {
        File f = new File(project, path);
        assertTrue(f.isFile(), path + " was not written");
        return new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8).replace("\r\n", "\n");
    }

    /** The @Test methods of the contract test classes in the directory. */
    private static int tests(File project, String dir) throws IOException {
        int n = 0;
        File[] files = new File(project, dir).listFiles();
        if (files == null) return 0;
        for (File f : files) {
            if (!f.getName().endsWith("ContractTest.java")) continue;
            String text = new String(Files.readAllBytes(f.toPath()), StandardCharsets.UTF_8).replace("\r\n", "\n");
            n += text.split("    @Test\n", -1).length - 1;
        }
        return n;
    }

    /** Every file of the project but the merge cache and the guides copied in: path -> text. */
    private static Map<String, String> tree(File project) throws IOException {
        Map<String, String> out = new TreeMap<String, String>();
        Path root = project.toPath();
        try (Stream<Path> all = Files.walk(root)) {
            for (Path p : (Iterable<Path>) all::iterator) {
                if (!Files.isRegularFile(p)) continue;
                String key = root.relativize(p).toString().replace('\\', '/');
                if (key.startsWith(".elasticore/")) continue;
                out.put(key, new String(Files.readAllBytes(p), StandardCharsets.UTF_8));
            }
        }
        return out;
    }

    private File project(String model, String testCode) throws IOException {
        return project(model, testCode, "jpa");
    }

    private File project(String model, String testCode, String mode) throws IOException {
        return project(model, testCode, mode, new String[0]);
    }

    /** A project whose env.yml's config holds these lines too (annotations: ...). */
    private File project(String model, String testCode, String mode, String... config) throws IOException {
        File dir = Files.createTempDirectory("elcore-contract").toFile();
        projects.add(dir);
        File blueprint = new File(dir, "src/main/resources/blueprint/shop");
        assertTrue(new File(blueprint, "model").mkdirs());
        List<String> env = new ArrayList<String>();
        env.add("elasticore:");
        env.add("  enable: true");
        env.add("  config:");
        env.add("    domainName: shop");
        env.add("    framework: springboot");
        env.add("    mode: " + mode);
        env.add("    j2ee: jakarta");
        if (testCode != null) env.add("    testCode: \"" + testCode + "\"");
        for (String line : config) env.add("    " + line);
        env.add("  namespace:");
        env.add("    base: com.acme.shop");
        env.add("");
        Files.write(
                new File(blueprint, "env.yml").toPath(), String.join("\n", env).getBytes(StandardCharsets.UTF_8));
        Files.write(new File(blueprint, "model/entity.yml").toPath(), model.getBytes(StandardCharsets.UTF_8));
        return dir;
    }

    /** The text of the generated file of that name under the package's directory. */
    private static String find(File project, String packageDir, String name) throws IOException {
        try (Stream<Path> all = Files.walk(project.toPath())) {
            for (Path p : (Iterable<Path>) all::iterator) {
                String path = p.toString().replace('\\', '/');
                if (path.contains("/src/main/") && path.contains(packageDir) && path.endsWith("/" + name)) {
                    return new String(Files.readAllBytes(p), StandardCharsets.UTF_8);
                }
            }
        }
        return "";
    }

    /** A second domain in the same project. */
    private static void addDomain(File project, String domain, String base, String model) throws IOException {
        File blueprint = new File(project, "src/main/resources/blueprint/" + domain);
        assertTrue(new File(blueprint, "model").mkdirs());
        String env = String.join(
                "\n",
                "elasticore:",
                "  enable: true",
                "  config:",
                "    domainName: " + domain,
                "    framework: springboot",
                "    mode: jpa",
                "    j2ee: jakarta",
                "    testCode: \"contract\"",
                "  namespace:",
                "    base: " + base,
                "");
        Files.write(new File(blueprint, "env.yml").toPath(), env.getBytes(StandardCharsets.UTF_8));
        Files.write(new File(blueprint, "model/entity.yml").toPath(), model.getBytes(StandardCharsets.UTF_8));
    }

