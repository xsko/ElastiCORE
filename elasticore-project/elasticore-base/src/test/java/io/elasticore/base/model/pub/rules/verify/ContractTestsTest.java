    @Test
    public void eachMoveIsTestedFromWhereItStartsAndRefusedElsewhere() throws Exception {
        File project = project(MODEL, "contract");
        String log = run(project, "hexagonal", "java");
        String t = read(project, "src/test/java/com/acme/shop/ShipmentContractTest.java");
        assertTrue(
                t.startsWith("// Initially generated by ElastiCORE; no longer managed - do not remove this line.\n"),
                t);
        assertTrue(t.contains("class ShipmentContractTest extends ShopContractSupport {"), t);
        // A new row starts where each lifecycle says, as the API shows it (@json(code)).
        assertTrue(
                t.contains("        MvcResult created = create(SHIPMENT, newShipment());\n"
                        + "        assertValue(created, \"status\", \"RDY\");\n"
                        + "        assertValue(created, \"fee\", \"DUE\");\n"),
                t);
        // The move, its state and its stamp.
        assertTrue(
                t.contains("    @DisplayName(\"send: status READY -> SENT\")\n"
                        + "    void sendFromReady() throws Exception {\n"
                        + "        Object id = createdId(SHIPMENT, newShipment(), \"shipmentId\");\n"
                        + "        MvcResult moved = command(SHIPMENT, id, \"send\", null);\n"
                        + "        assertMoved(moved);\n"
                        + "        assertValue(moved, \"status\", \"SNT\");\n"
                        + "        assertStamped(moved, \"sentAt\");\n"),
                t);
        // One command, two lifecycles: the row is brought to where both allow it.
        assertTrue(
                t.contains("    @DisplayName(\"cancel: status READY -> CANCELLED, fee PAID -> REFUNDED\")\n"
                        + "    void cancelFromReadyPaid() throws Exception {\n"
                        + "        Object id = createdId(SHIPMENT, newShipment(), \"shipmentId\");\n"
                        + "        given(command(SHIPMENT, id, \"pay\", null));\n"
                        + "        MvcResult moved = command(SHIPMENT, id, \"cancel\", null);\n"),
                t);
        // Refused from a state the move does not list, by the code of the lifecycle that refuses.
        assertTrue(
                t.contains(
                        "        given(command(SHIPMENT, id, \"send\", null));\n"
                                + "        assertRefused(command(SHIPMENT, id, \"send\", null), 409, \"state.Shipment.status.send\");\n"),
                t);
        assertTrue(
                t.contains(
                        "    void cancelIsRefusedWhenFeeIsDue() throws Exception {\n"
                                + "        Object id = createdId(SHIPMENT, newShipment(), \"shipmentId\");\n"
                                + "        assertRefused(command(SHIPMENT, id, \"cancel\", null), 409, \"state.Shipment.fee.cancel\");\n"),
                t);
        // Only the other lifecycle refuses: send then pay, and cancel is refused by status alone.
        assertTrue(
                t.contains(
                        "        given(command(SHIPMENT, id, \"send\", null));\n"
                                + "        given(command(SHIPMENT, id, \"pay\", null));\n"
                                + "        assertRefused(command(SHIPMENT, id, \"cancel\", null), 409, \"state.Shipment.status.cancel\");\n"),
                t);
        assertFalse(t.contains("Assumptions"), t);
        assertTrue(log.contains("contract     src/test/java/com/acme/shop/ShipmentContractTest.java  WROTE"), log);
    }

    @Test
    public void eachConstraintIsTestedAtItsBoundaryAndOnePast() throws Exception {
        File project = project(MODEL, "contract");
        run(project, "hexagonal", "java");
        String t = read(project, "src/test/java/com/acme/shop/ShipmentContractTest.java");
        // The row each test starts from: what the model requires, and what its promise reads.
        assertTrue(t.contains("        return obj(\"carrier\", text(12), \"price\", num(\"0.01\"));\n"), t);
        assertTrue(
                t.contains(
                        "assertFieldError(post(SHIPMENT, withValue(newShipment(), \"carrier\", null)), \"carrier\", \"NotNull\");"),
                t);
        assertTrue(
                t.contains(
                        "assertCreated(post(SHIPMENT, withValue(newShipment(), \"carrier\", text(30))));\n"
                                + "        assertFieldError(post(SHIPMENT, withValue(newShipment(), \"carrier\", text(31))), \"carrier\", \"Size\");"),
                t);
        assertTrue(
                t.contains(
                        "assertCreated(post(SHIPMENT, withValue(newShipment(), \"weight\", num(\"1\"))));\n"
                                + "        assertFieldError(post(SHIPMENT, withValue(newShipment(), \"weight\", num(\"0\"))), \"weight\", \"Min\");"),
                t);
        assertTrue(
                t.contains(
                        "assertCreated(post(SHIPMENT, withValue(newShipment(), \"weight\", num(\"500\"))));\n"
                                + "        assertFieldError(post(SHIPMENT, withValue(newShipment(), \"weight\", num(\"501\"))), \"weight\", \"Max\");"),
                t);
        // A value made from the pattern, and checked against it, passes; one that does not match is refused.
        assertTrue(
                t.contains(
                        "assertCreated(post(SHIPMENT, withValue(newShipment(), \"code\", vary(\"AA000\", \"ABCDEFGHIJKLMNOPQRSTUVWXYZ\","
                                + " \"ABCDEFGHIJKLMNOPQRSTUVWXYZ\", \"0123456789\", \"0123456789\", \"0123456789\"))));\n"
                                + "        assertFieldError(post(SHIPMENT, withValue(newShipment(), \"code\", \"!\")), \"code\", \"Pattern\");"),
                t);
        // Its length: no value of 8 characters matches, so only one past it is sent - refused whatever it holds.
        assertTrue(t.contains("@DisplayName(\"code: 9 characters are refused (400 Size)\")"), t);
        assertTrue(
                t.contains(
                        "assertFieldError(post(SHIPMENT, withValue(newShipment(), \"code\", text(9))), \"code\", \"Size\");"),
                t);
        // The invariant: its boundary passes, one past it is refused with its code (422).
        assertTrue(
                t.contains(
                        "@DisplayName(\"@invariant(price > 0): 0.01 passes, 0 is refused (422 invariant.Shipment.price-gt-0)\")"),
                t);
        assertTrue(
                t.contains(
                        "assertRefused(post(SHIPMENT, withValue(newShipment(), \"price\", num(\"0\"))), 422, \"invariant.Shipment.price-gt-0\");"),
                t);
        // @min(0) on price: its boundary breaks the invariant, so it is not tested - and said.
        assertFalse(t.contains("priceMin"), t);
        // Never a message.
        assertFalse(t.contains("\"message\""), t);
    }

