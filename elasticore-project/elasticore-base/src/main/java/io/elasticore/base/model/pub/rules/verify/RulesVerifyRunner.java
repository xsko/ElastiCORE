package io.elasticore.base.model.pub.rules.verify;

import io.elasticore.base.ECoreModelContext;
import io.elasticore.base.ModelDomain;
import io.elasticore.base.model.ECoreModel;
import io.elasticore.base.model.ModelComponentItems;
import io.elasticore.base.model.core.BaseECoreModelContext;
import io.elasticore.base.model.entity.Entity;
import io.elasticore.base.model.loader.FileBasedModelLoader;
import io.elasticore.base.model.pub.rules.EntitySpec;
import io.elasticore.base.model.pub.rules.RuleCatalog;
import io.elasticore.base.model.pub.rules.SourceCode;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileInputStream;
import java.io.IOException;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Compares the output of the NEW rule-based pipeline against the sources
 * that the EXISTING 2.x pipeline generated (and which are committed in the
 * project), without writing any file.
 *
 * Invoked by the elcoreRulesCheck gradle task, alongside - never instead
 * of - the existing elcore task:
 *
 *   ./gradlew elcoreRulesCheck [-Pdomain=content] [-Pstrict]
 *
 * Verdicts per entity and artifact:
 *   MATCH  - rule output is identical (full file for repository/service/
 *            controller minus the ecd hash line and the generated-once
 *            marker comment; field block for entities)
 *   DIFF   - output differs; the pattern is not (or wrongly) ported
 *   SKIP   - artifact not applicable or no comparison anchor
 *
 * DTO and mapper artifacts are verified by unit tests with hand-built
 * specs; runner-level verification for them requires the derived DTO
 * model, which the 2.x pipeline completes at publish time (not load time),
 * and is therefore a next-phase item.
 */
public final class RulesVerifyRunner {

    private static final String MARKER = "Initially generated by ElastiCORE";

    private int match = 0;
    private int diff = 0;
    private int skip = 0;
    private int accepted = 0;
    private final List<String> diffDetails = new ArrayList<String>();
    private final List<String> acceptedDetails = new ArrayList<String>();

    /**
     * Artifacts the rules deliberately no longer reproduce, and why.
     *
     * A difference listed here is a decision, not an unfinished port, so it
     * is reported apart from the ones still to be explained and does not
     * fail -Pstrict. Anything not listed still has to match, which is what
     * keeps the check worth running.
     */
    private static final java.util.Map<String, String> ACCEPTED_DIFFS;
    static {
        java.util.Map<String, String> m = new java.util.LinkedHashMap<String, String>();
        String relationFlattening =
                "2.x flattened only the first of two identically declared @ManyToOne "
                + "relations, so the second could not be searched at all; the rules "
                + "flatten both. Additive: the extra id is a new search property.";
        m.put("OrderItem/srchdto", relationFlattening);
        m.put("Comment/srchdto", relationFlattening);
        ACCEPTED_DIFFS = java.util.Collections.unmodifiableMap(m);
    }

    private final String srcRoot;
    private final boolean verbose;

    /** All loaded domain models: enum references resolve across domains in 2.x. */
    private final List<ECoreModel> allModels = new ArrayList<ECoreModel>();

    private RulesVerifyRunner(String srcRoot, boolean verbose) {
        this.srcRoot = srcRoot;
        this.verbose = verbose;
    }

    public static void main(String[] args) throws Exception {
        // The compatible check never carries value objects in DTOs, whatever
        // ran before it in this JVM.
        SpecFactory.valueObjectsInDto(false);
        SpecFactory.rootsSplitByDefault(false);
        SpecFactory.referenceRequiredByKey(false);
        String basePath = System.getProperty("elasticore.base.path");
        if (basePath == null) basePath = System.getProperty("user.dir");

        String srcRoot = args.length > 0 ? args[0] : basePath + "/src/main/java";
        String blueprintRoot = basePath + "/src/main/resources/blueprint";
        boolean verbose = Boolean.getBoolean("elasticore.rules.verbose");
        boolean strict = Boolean.getBoolean("elasticore.rules.strict");
        String domainFilter = System.getProperty("elasticore.domain");

        System.out.println("[RulesCheck] source root : " + srcRoot);
        System.out.println("[RulesCheck] blueprint   : " + blueprintRoot);

        BlueprintLoader loader = BlueprintLoader.load(blueprintRoot);
        if (loader.isEmpty()) {
            System.out.println("[RulesCheck] no blueprint directory found");
            System.exit(1);
            return;
        }
        Map<String, ECoreModelContext> contexts = loader.contexts();

        RulesVerifyRunner runner = new RulesVerifyRunner(srcRoot, verbose);
        runner.allModels.addAll(loader.allModels());
        for (Map.Entry<String, ECoreModelContext> en : contexts.entrySet()) {
            String domainDirName = en.getKey();
            if (domainFilter != null && !domainFilter.contains(domainDirName)) continue;
            runner.verifyContext(domainDirName, en.getValue());
        }

        runner.printSummary();
        if (strict && runner.diff > 0) {
            System.exit(1);
        }
    }

    // ------------------------------------------------------------------

    private void verifyContext(String domainDirName, ECoreModelContext ctx) {
        System.out.println();
        System.out.println("[" + domainDirName + "]");
        for (String domainName : ctx.getInternalDomainNames()) {
            ModelDomain domain = ctx.getDomain(domainName);
            if (domain == null) continue;
            ECoreModel model = domain.getModel();

            ModelComponentItems<Entity> entities = model.getEntityModels().getItems();
            while (entities.hasNext()) {
                Entity entity = entities.next();
                verifyEntity(domainDirName, entity, model);
            }

            verifyDtos(domainDirName, model);
            verifyEnums(model);
        }
    }

    /**
     * The DTO artifacts of a domain. Which of the two a declaration produces
     * is decided the way the generator decides it: an @searchable DTO is the
     * search shape, everything else the plain one.
     */
    private void verifyDtos(String domainDirName, ECoreModel model) {
        if (model.getDataTransferModels() == null) return;

        ModelComponentItems<io.elasticore.base.model.dto.DataTransfer> dtos =
                model.getDataTransferModels().getItems();
        for (int i = 0; i < dtos.size(); i++) {
            io.elasticore.base.model.dto.DataTransfer dto = dtos.get(i);
            String name = dto.getIdentity().getName();
            // Only what fromDto carries, as the generator has it: registering
            // every loaded domain's enums here would tell a DTO of a domain
            // that declares none that it has some, and the import line follows
            // from that.
            EntitySpec spec = SpecFactory.fromDto(dto, model, domainDirName);

            boolean searchable = dto.getMetaInfo().hasMetaAnnotation("searchable");
            String target = searchable ? "srchdto" : "dto";
            String verdict = searchable
                    ? verifySkeleton(spec, target, model.getNamespace("dto"), name, false,
                            "jpa-searchdto", "jpa-searchdto-file")
                    : verifySkeleton(spec, target, model.getNamespace("dto"), name, false,
                            "jpa-dto", "jpa-dto-file");
            System.out.println(String.format("  %-24s %s=%s", name, target, verdict));
        }
    }

    /** One file per declared enumeration. */
    private void verifyEnums(ECoreModel model) {
        if (model.getEnumModels() == null) return;

        ModelComponentItems<io.elasticore.base.model.enums.EnumModel> enums =
                model.getEnumModels().getItems();
        for (int i = 0; i < enums.size(); i++) {
            io.elasticore.base.model.enums.EnumModel em = enums.get(i);
            final String name = em.getIdentity().getName();
            final io.elasticore.base.model.pub.rules.EnumSpec spec = SpecFactory.fromEnum(em, model);
            String verdict = compareToGolden(name, "enum",
                    model.getNamespace("enumeration"), name, false,
                    new Rendering() {
                        public String render() {
                            return RuleCatalog.standard().engineFor("jpa-enum")
                                    .run(spec, "enum").render();
                        }
                    });
            System.out.println(String.format("  %-24s enum=%s", name, verdict));
        }
    }

    private void verifyEntity(String domainDirName, Entity entity, ECoreModel model) {
        String name = entity.getIdentity().getName();
        EntitySpec spec = SpecFactory.fromEntity(entity, model, domainDirName);

        // Enum references resolve across every loaded domain, as in 2.x.
        for (ECoreModel m : allModels) {
            SpecFactory.registerEnums(spec, m);
        }

        boolean exposed = entity.getMetaInfo().hasMetaAnnotation("expose");
        boolean serviced = exposed || entity.getMetaInfo().hasMetaAnnotation("service");
        boolean hasPk = spec.pkField() != null;

        StringBuilder line = new StringBuilder(String.format("  %-24s", name));

        line.append(" entity=").append(verifyEntityFieldBlock(spec, model));

        if (serviced && hasPk) {
            line.append(" repository=").append(
                    verifySkeleton(spec, "repository",
                            model.getNamespace("repository"),
                            String.format("%sRepository", name), false));
            line.append(" service=").append(
                    verifySkeleton(spec, "service_extend",
                            model.getNamespace("service"),
                            String.format("%sService", name), true));
        }
        if (exposed && hasPk) {
            line.append(" controller=").append(
                    verifySkeleton(spec, "control",
                            model.getNamespace("control"),
                            String.format("%sController", name), true));
        }
        System.out.println(line);
    }

    /**
     * Field-block comparison for the entity artifact. Entities with a PK
     * anchor at the first @Id line (the PK constructor precedes it); entities
     * without one (abstract parents, embeddables) anchor right after the
     * class declaration, which nothing precedes.
     */
    private String verifyEntityFieldBlock(EntitySpec spec, ECoreModel model) {
        File file = sourceFile(model.getNamespace("entity"), spec.getName());
        if (file == null) {
            skip++;
            return "SKIP(no-file)";
        }
        try {
            SourceCode code = RuleCatalog.standard().engineFor("jpa-entity").run(spec);
            String actual = code.renderFieldBlock();
            String expected = spec.pkField() != null
                    ? extractTabBlock(file, "@Id")
                    : extractClassBodyBlock(file);
            if (expected == null) {
                skip++;
                return "SKIP(no-anchor)";
            }
            return verdict(spec.getName() + "/entity", expected, actual, false);
        } catch (Exception e) {
            diff++;
            diffDetails.add(spec.getName() + "/entity: " + e);
            return "DIFF(error)";
        }
    }

    /** Full-file comparison for template-skeleton artifacts. */
    private String verifySkeleton(EntitySpec spec, String target,
                                  String pkg, String className, boolean markerException) {
        return verifySkeleton(spec, target, pkg, className, markerException,
                "jpa-repository", "spring-service-extend", "spring-controller");
    }

    /** The same, for an artifact rendered by rule sets of its own. */
    private String verifySkeleton(EntitySpec spec, String target,
                                  String pkg, String className, boolean markerException,
                                  String... ruleSets) {
        return compareToGolden(spec.getName(), target, pkg, className, markerException,
                new Rendering() {
                    public String render() {
                        return RuleCatalog.standard().engineFor(ruleSets).run(spec, target).render();
                    }
                });
    }

    /** Renders one artifact; the spec type is the caller's business. */
    private interface Rendering {
        String render();
    }

    /**
     * Compares a rendered artifact against the committed source of the same
     * name. The rendering is deferred so that every spec kind - entity, DTO,
     * enum, domain - reaches the same comparison without this method having to
     * know which RuleEngine.run overload applies.
     */
    private String compareToGolden(String name, String target, String pkg, String className,
                                   boolean markerException, Rendering rendering) {
        File file = sourceFile(pkg, className);
        if (file == null) {
            skip++;
            return "SKIP(no-file)";
        }
        try {
            List<String> expectedLines = readLines(file);
            if (!expectedLines.isEmpty() && expectedLines.get(0).startsWith("//ecd:")) {
                expectedLines = expectedLines.subList(1, expectedLines.size());
            }
            String actual = rendering.render();
            String expected = join(stripTrailingBlank(expectedLines));
            String actualNorm = join(stripTrailingBlank(toLines(actual)));

            return verdict(name + "/" + target, expected, actualNorm, markerException);
        } catch (Exception e) {
            diff++;
            diffDetails.add(name + "/" + target + ": " + e);
            return "DIFF(error)";
        }
    }

    private String verdict(String label, String expected, String actual, boolean markerException) {
        List<String> exp = toLines(expected);
        List<String> act = toLines(actual);

        List<String> diffs = new ArrayList<String>();
        int max = Math.max(exp.size(), act.size());
        for (int i = 0; i < max; i++) {
            String e = i < exp.size() ? exp.get(i) : "<missing>";
            String a = i < act.size() ? act.get(i) : "<missing>";
            if (e.equals(a)) continue;
            if (markerException && e.contains(MARKER) && a.contains(MARKER)) continue;
            diffs.add(String.format("    line %4d  expected: %s%n               actual: %s", i + 1, e, a));
        }
        if (diffs.isEmpty()) {
            match++;
            return "MATCH";
        }
        String reason = ACCEPTED_DIFFS.get(label);
        if (reason != null) {
            accepted++;
            acceptedDetails.add(label + " (" + diffs.size() + " lines): " + reason);
            return "ACCEPTED(" + diffs.size() + ")";
        }
        diff++;
        StringBuilder d = new StringBuilder(label + " (" + diffs.size() + " lines)");
        int limit = verbose ? diffs.size() : Math.min(3, diffs.size());
        for (int i = 0; i < limit; i++) d.append(System.lineSeparator()).append(diffs.get(i));
        diffDetails.add(d.toString());
        return "DIFF(" + diffs.size() + ")";
    }

    private void printSummary() {
        System.out.println();
        System.out.println("=== RulesCheck summary: " + match + " MATCH / "
                + diff + " DIFF / " + accepted + " ACCEPTED / " + skip + " SKIP ===");
        if (!acceptedDetails.isEmpty()) {
            System.out.println();
            System.out.println("--- accepted differences (deliberate; see the reason) ---");
            for (String a : acceptedDetails) System.out.println("  " + a);
        }
        if (!diffDetails.isEmpty()) {
            System.out.println();
            System.out.println("--- differences (first lines; -Pverbose for all) ---");
            for (String d : diffDetails) {
                System.out.println("  " + d);
            }
        }
    }

    // ------------------------------------------------------------------
    // file helpers
    // ------------------------------------------------------------------

    private File sourceFile(String pkg, String className) {
        if (pkg == null) return null;
        File f = new File(srcRoot + "/" + pkg.replace('.', '/') + "/" + className + ".java");
        return f.isFile() ? f : null;
    }

    /**
     * Field block of an entity without a PK: from the first non-blank line
     * after the class declaration to before the last brace.
     */
    private String extractClassBodyBlock(File src) throws IOException {
        List<String> lines = readLines(src);
        int declIdx = -1;
        int end = -1;
        for (int i = 0; i < lines.size(); i++) {
            String t = lines.get(i).trim();
            if (declIdx < 0 && t.contains(" class ") && t.endsWith("{")) declIdx = i;
            if (t.equals("}")) end = i;
        }
        if (declIdx < 0 || end <= declIdx) return null;

        int start = declIdx + 1;
        while (start < end && lines.get(start).trim().isEmpty()) start++;
        if (start >= end) return null;

        StringBuilder sb = new StringBuilder();
        for (int i = start; i < end; i++) {
            String line = lines.get(i);
            if (line.startsWith("\t")) line = line.substring(1);
            if (line.trim().isEmpty()) line = "";
            sb.append(line).append('\n');
        }
        return sb.toString();
    }

    /** From the first line whose trim equals the anchor to before the last brace. */
    private String extractTabBlock(File src, String anchor) throws IOException {
        List<String> lines = readLines(src);
        int start = -1;
        int end = -1;
        for (int i = 0; i < lines.size(); i++) {
            String t = lines.get(i).trim();
            if (start < 0 && t.equals(anchor)) start = i;
            if (t.equals("}")) end = i;
        }
        if (start <= 0 || end <= start) return null;
        StringBuilder sb = new StringBuilder();
        for (int i = start; i < end; i++) {
            String line = lines.get(i);
            if (line.startsWith("\t")) line = line.substring(1);
            if (line.trim().isEmpty()) line = "";
            sb.append(line).append('\n');
        }
        return sb.toString();
    }

    private static List<String> readLines(File f) throws IOException {
        List<String> lines = new ArrayList<String>();
        BufferedReader r = new BufferedReader(
                new InputStreamReader(new FileInputStream(f), StandardCharsets.UTF_8));
        try {
            String line;
            while ((line = r.readLine()) != null) lines.add(line);
        } finally {
            r.close();
        }
        return lines;
    }

    private static List<String> toLines(String text) {
        List<String> list = new ArrayList<String>();
        for (String s : text.replace("\r\n", "\n").split("\n", -1)) list.add(s);
        return list;
    }

    private static List<String> stripTrailingBlank(List<String> lines) {
        List<String> r = new ArrayList<String>(lines);
        while (!r.isEmpty() && r.get(r.size() - 1).trim().isEmpty()) r.remove(r.size() - 1);
        return r;
    }

    private static String join(List<String> lines) {
        StringBuilder sb = new StringBuilder();
        for (String l : lines) sb.append(l).append('\n');
        return sb.toString();
    }
}
