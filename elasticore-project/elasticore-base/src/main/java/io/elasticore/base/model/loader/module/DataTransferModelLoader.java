public class DataTransferModelLoader extends AbstractModelLoader implements ConstantParam, ModelLoader<DataTransfer> {


    public boolean loadModel(ModelLoaderContext ctx, FileSource source) {
        return loadModel(ctx, source.getInfoMap());
    }

    public boolean loadModel(ModelLoaderContext ctx, Map<String, Map> map) {


        if (map.containsKey(ConstantParam.KEYNAME_DTO)) {
            Map entityMap = map.get(ConstantParam.KEYNAME_DTO);
            loadModel(ctx, ctx.getDataTransferItems(), entityMap);
        }

        if (map.containsKey(ConstantParam.KEYNAME_ENTITY)) {
            Map entityMap = map.get(ConstantParam.KEYNAME_ENTITY);
            loadModel(ctx, ctx.getDataTransferItems(), entityMap);
            loadCommandDtos(ctx, ctx.getDataTransferItems(), entityMap);
        }


        return false;
    }

    public void loadModel(ModelLoaderContext ctx, Items<DataTransfer> items, Map<String, LinkedHashMap> dtoInfoMap) {

        this.setModelLoaderContext(ctx);

        dtoInfoMap.forEach((entityNm, value) -> {
            List<DataTransfer> dtos = loadDataTransfer(ctx, entityNm, value);
            for(DataTransfer dto: dtos) {
                DataTransfer dataTransfer = items.find(dto.getIdentity());
                if( dataTransfer == null) {
                    items.addItem(dto);
                }
                else {
                    // Identity collision: an explicitly-declared DTO must take precedence
                    // over an auto-generated one (@autogen), regardless of load order.
                    // Otherwise an @expose/@service entity's auto-generated {Entity}SrchDTO
                    // (or {Entity}DTO) would shadow a user's hand-declared DTO of the same
                    // name and ignore its declared fields.
                    boolean newIsAutoGen = dto.getMetaInfo().hasMetaAnnotation(EntityAnnotation.AUTOGENERATED);
                    boolean existIsAutoGen = dataTransfer.getMetaInfo().hasMetaAnnotation(EntityAnnotation.AUTOGENERATED);
                    if (existIsAutoGen && !newIsAutoGen) {
                        // Replace the auto-generated DTO with the explicit declaration.
                        items.addItem(dto);
                    }
                    // Otherwise keep the existing item: either the explicit declaration is
                    // already registered (explicit wins), or it is a same-kind duplicate
                    // where the first registered entry is retained.
                }
            }
        });
    }


    /**
     * A business command with parameters is sent as a DTO of its own -
     * SalesOrder's "ship" as SalesOrderShipCommand - declared here as if the
     * DSL had written it, so it is generated, validated and imported like any
     * other. A DTO the DSL declares under the same name wins.
     */
    @SuppressWarnings("unchecked")
    private void loadCommandDtos(ModelLoaderContext ctx, Items<DataTransfer> items, Map<String, Object> entityMap) {
        for (Map.Entry<String, Object> en : entityMap.entrySet()) {
            if (!(en.getValue() instanceof Map)) continue;
            Object commands = ((Map<String, Object>) en.getValue()).get(EntityModelLoader.PROPERTY_COMMANDS);
            if (!(commands instanceof Map)) continue;
            for (Map.Entry<String, Object> cmd : ((Map<String, Object>) commands).entrySet()) {
                if (cmd.getKey() == null || cmd.getKey().trim().isEmpty()) continue;
                if (!(cmd.getValue() instanceof Map) || ((Map<?, ?>) cmd.getValue()).isEmpty()) continue;
                String name = EntityModelLoader.commandDtoName(en.getKey(), cmd.getKey().trim());
                Map<String, Object> declared = new LinkedHashMap<String, Object>();
                declared.put(PROPERTY_META, "dto");
                declared.put(PROPERTY_FIELDS, new LinkedHashMap<String, Object>((Map<String, Object>) cmd.getValue()));
                for (DataTransfer dto : loadDataTransfer(ctx, name, declared)) {
                    if (items.find(dto.getIdentity()) == null) items.addItem(dto);
                }
            }
        }
    }

    /**
     * transform meta data to extend function
     *
     * @param entityMap
     */
    protected void transfer(Map<String, Object> entityMap) {
        String meta = (String) entityMap.get("meta");
        if(meta!=null) {
            if( (meta.indexOf("@dto")>=0  || meta.indexOf("@pageable")>=0  || meta.indexOf("@searchable")>=0 )
                && !meta.contains("@expose") && !meta.contains("@service") )
                return;

            // Handle both @expose and @service annotations
            if(meta.contains("@expose") || meta.contains("@service")) {
                StringBuilder annotations = new StringBuilder();
                
                // Preserve the original annotation (@expose or @service)
                if(meta.contains("@expose")) {
                    annotations.append("@expose");
                } else if(meta.contains("@service")) {
                    annotations.append("@service");
                }

                if (!meta.contains("@dto")) {
                    annotations.append(" @dto");
                }
                if (!meta.contains("@searchable")) {
                    annotations.append(" @searchable");
                }
                if (!meta.contains("@pageable")) {
                    annotations.append(" @pageable");
                }

                // @expose(pageSize=50, methods="...") - or 2.x's @expose(50): the page size goes to
                // @pageable, methods stays on @expose. Without this, everything in the brackets went
                // to the @pageable written last, and a page size beside methods= was lost (20).
                java.util.regex.Matcher args = EXPOSE_ARGS.matcher(meta);
                if (args.find() && args.group(1).contains("=")) {
                    String pageSize = null;
                    String methods = null;
                    for (String arg : splitArgs(args.group(1))) {
                        int eq = arg.indexOf('=');
                        String key = eq < 0 ? "" : arg.substring(0, eq).trim();
                        String value =
                                eq < 0 ? arg.trim() : arg.substring(eq + 1).trim();
                        if (eq < 0 || "pageSize".equalsIgnoreCase(key)) pageSize = value;
                        else if ("methods".equalsIgnoreCase(key)) methods = value;
                    }
                    String expose = methods == null ? "@expose" : "@expose(methods=" + methods + ")";
                    String rest = annotations.toString().substring("@expose".length());
                    if (pageSize != null && rest.endsWith("@pageable")) rest = rest + "(" + pageSize + ")";
                    meta = meta.substring(0, args.start()) + expose + rest + meta.substring(args.end());
                } else {
                    // Replace both @expose and @service patterns
                    meta = meta.replaceAll("@expose\\b", annotations.toString());
                }
                meta = meta.replaceAll("@service\\b", annotations.toString());
                entityMap.put("meta", meta);
            }
        }
    }

    /** The brackets of @expose(...), quotes and all: methods="a,b" has no bracket of its own. */
    private static final java.util.regex.Pattern EXPOSE_ARGS =
            java.util.regex.Pattern.compile("@expose\\s*\\(([^)]*)\\)");

    /** The arguments of an annotation, split at the commas outside quotes. */
    static List<String> splitArgs(String text) {
        List<String> out = new ArrayList<>();
        StringBuilder cur = new StringBuilder();
        char quote = 0;
        for (int i = 0; i < text.length(); i++) {
            char ch = text.charAt(i);
            if (quote != 0) {
                if (ch == quote) quote = 0;
            } else if (ch == '"' || ch == '\'') {
                quote = ch;
            } else if (ch == ',') {
                if (cur.toString().trim().length() > 0) out.add(cur.toString().trim());
                cur.setLength(0);
                continue;
            }
            cur.append(ch);
        }
        if (cur.toString().trim().length() > 0) out.add(cur.toString().trim());
        return out;
    }

    protected List<DataTransfer> loadDataTransfer(ModelLoaderContext ctx, String entityNm, Map<String, Object> entityMap) {

        transfer(entityMap);
        List<DataTransfer> result = new ArrayList<>();

        MetaInfo metaInfo = parseMetaInfoObject(entityMap, KEYNAME_DTO, entityNm);

        Map fields = (Map) entityMap.get(PROPERTY_FIELDS);
        Items<Field> fieldItems = null;
        if (fields != null)
            fieldItems = parseField(fields, entityNm ,metaInfo);


        // Handles the "dto" annotation declared within the entity model
        if( "entity".equals(metaInfo.getMetaAnnotationValue(EntityAnnotation.META_TYPE))) {

            if( metaInfo.hasMetaAnnotation(EntityAnnotation.META_DTO)) {

                Items<Field> items = Items.create(Field.class);

                // for fields
                if(fieldItems!=null) {
                    List<Field> itemList = fieldItems.getItemList();
                    for(Field field : itemList) {

                        TypeInfo fieldTypeInfo = field.getTypeInfo();

                        if(!fieldTypeInfo.isBaseType()) {

                            boolean isProcess = true;

                            String newFieldType = field.getTypeInfo().getDefaultTypeName();

                            if(!fieldTypeInfo.isList()) {
                                // 20241213 Until enum selection is implemented
                                //if(ctx.getEnumModelItems().findByName(fieldTypeInfo.getInitTypeInfo())!=null)
                                {
                                    isProcess = false;
                                }

                                isProcess = true;
                            }else {
                                isProcess = false;

                                String dtoType = field.getAnnotationValue(EntityAnnotation.DTO_TYPE);
                                if(StringUtils.hasValue(dtoType)) {
                                    //TypeInfo dtoTypeInfo = new TypeInfo(dtoType);

                                    newFieldType = dtoType;
                                    isProcess = true;
                                }


                            }

                            if(isProcess) {

                                Annotation annotation = Annotation.create(EntityAnnotation.META_DEFERRED);
                                Map<String, Annotation> annotationMap = field.getAnnotationMap();
                                annotationMap.put(annotation.getName(), annotation);

                                items.addItem(
                                        Field.builder()
                                                .name(field.getName())
                                                .parentMetaInfo(metaInfo)
                                                .type(newFieldType)
                                                .annotationMap(annotationMap).build()
                                );

                            /*
                            items.addItem(
                                    Field.builder().name(field.getName()).type(field.getTypeInfo().getDefaultTypeName()+"DTO").build()
                            );

                             */
                            }


                        }

                    }
                }

                // for @searchResult
                if(metaInfo.hasMetaAnnotation(DataTransferAnnotation.META_SEARCH_RESULT)) {
                    Object metaInfoObj = entityMap.get(PROPERTY_META);

                    if(metaInfoObj instanceof String) {
                        //String lineData = (String) entityMap.get(PROPERTY_META) +" @dto";
                        String lineData = "entity @dto";

                        String newLineData = lineData +String.format("@searchResult(%s)",entityNm);


                        entityMap.put(PROPERTY_META, newLineData);
                        String mainClassNm = entityNm+"ResultDTO";
                        MetaInfo metaInfo2 = parseMetaInfoObject(entityMap ,"dto", mainClassNm);
                        result.add(DataTransfer.create(ctx.getDomainId(), mainClassNm, items, metaInfo2));

                    }
                }


                boolean isPagable = metaInfo.hasMetaAnnotation(EntityAnnotation.META_PAGEABLE);

                String pageSizeVal = metaInfo.getMetaAnnotationValue(EntityAnnotation.META_PAGEABLE);
                if(pageSizeVal==null)
                    pageSizeVal = "20";


                Object metaInfoObj = entityMap.get(PROPERTY_META);

                if(metaInfoObj instanceof String) {
                    //String lineData = (String) entityMap.get(PROPERTY_META) +" @dto";
                    String lineData = "entity @dto @"+EntityAnnotation.AUTOGENERATED+" ";

                    String expoeAnnotation = "@"+EntityAnnotation.META_EXPOSE;
                    if(metaInfoObj.toString().indexOf(expoeAnnotation)>=0) {
                        lineData = lineData+" "+expoeAnnotation;
                    }

                    // Propagate @jsonview from entity meta to auto-generated DTO
                    String entityMetaStr = metaInfoObj.toString();
                    if(entityMetaStr.contains("@jsonview")) {
                        java.util.regex.Pattern jsonviewPat = java.util.regex.Pattern.compile("@jsonview(?:\\(([^)]*)\\))?");
                        java.util.regex.Matcher jsonviewMat = jsonviewPat.matcher(entityMetaStr);
                        if(jsonviewMat.find()) {
                            lineData = lineData + " " + jsonviewMat.group(0);
                        }
                    }

                    String newLineData = lineData +String.format("@template(%s)",entityNm);


                    entityMap.put(PROPERTY_META, newLineData);
                    String mainClassNm = entityNm+"DTO";
                    metaInfo = parseMetaInfoObject(entityMap ,"dto", mainClassNm);
                    result.add(DataTransfer.create(ctx.getDomainId(), mainClassNm, items, metaInfo));


                    if(isPagable) {
                        newLineData = lineData +
                                String.format("@searchable(entity=%s, pageSize=%s)", entityNm,pageSizeVal);
                    }else {
                        newLineData = lineData +String.format("@searchable(%s)", entityNm);
                    }



                    entityMap.put(PROPERTY_META, newLineData);
                    String mainClassName = entityNm+"SrchDTO";
                    metaInfo = parseMetaInfoObject(entityMap ,"dto", mainClassName);
                    result.add(DataTransfer.create(ctx.getDomainId(), mainClassName, items, metaInfo));

                    return result;
                }


            }
            else {
                return result;
            }
        }

        result.add(DataTransfer.create(ctx.getDomainId(), entityNm, fieldItems, metaInfo));
        return result;
    }



}
