package io.elasticore.base.model.pub.rules.graphql;

import io.elasticore.base.model.ECoreModel;
import io.elasticore.base.model.ModelComponentItems;
import io.elasticore.base.model.entity.Entity;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * What the domains that turn GraphQL on have to agree on, checked once per
 * run, and the endpoint path they name, left for the running application.
 *
 * Spring for GraphQL serves one schema at one path for the application, so
 * every domain's operations and types share one namespace and one endpoint:
 * two domains naming different paths, or both serving an entity of one name,
 * cannot both be served. The build refuses them here, naming the domains,
 * before anything is compiled.
 */
public final class GraphQlSettings {

    /** The properties file the runtime's configuration reads below the application's own. */
    public static final String PROPERTIES = "src/main/resources/graphql/elasticore-graphql.properties";

    static final String HEADER = "# Generated by ElastiCORE from the domains' env.yml (graphql.path) - do not edit.";

    private GraphQlSettings() {}

    /** Whether this domain's env.yml turns GraphQL on. */
    public static boolean enabled(ECoreModel model) {
        Object v = model.getConfig("graphql.enable");
        return v != null && GraphQlRules.enabled(String.valueOf(v));
    }

    /** The path a domain names, or null. */
    public static String path(ECoreModel model) {
        Object v = model.getConfig("graphql.path");
        if (v == null) return null;
        String p = String.valueOf(v).trim();
        return p.isEmpty() ? null : p;
    }

    /**
     * What the GraphQL domains of one application disagree on: a path, or an
     * entity both serve. Each finding names the domains and their env.yml.
     */
    public static List<String> problems(List<ECoreModel> models) {
        List<String> out = new ArrayList<String>();
        String path = null;
        String pathDomain = null;
        Map<String, String> servedBy = new LinkedHashMap<String, String>();
        for (ECoreModel m : models) {
            if (!enabled(m)) continue;
            String domain = m.getInternalDomainName();
            String p = path(m);
            if (p != null) {
                if (path == null) {
                    path = p;
                    pathDomain = domain;
                } else if (!path.equals(p)) {
                    out.add(String.format(
                            "[elcore3] graphql: domain %s names path %s and domain %s names %s"
                                    + " (env.yml graphql.path of each) - the application serves one GraphQL"
                                    + " endpoint; name the same path, or name it in one of them",
                            pathDomain, path, domain, p));
                }
            }
            ModelComponentItems<Entity> entities = m.getEntityModels().getItems();
            for (int i = 0; i < entities.size(); i++) {
                Entity e = entities.get(i);
                if (!e.getMetaInfo().hasMetaAnnotation("expose")) continue;
                String name = e.getIdentity().getName();
                String other = servedBy.get(name);
                if (other != null && !other.equals(domain)) {
                    out.add(String.format(
                            "[elcore3] graphql: domains %s and %s both serve an entity %s"
                                    + " (env.yml graphql.enable of each) - one GraphQL schema has one type %s and one"
                                    + " query %s; rename one of them, or turn GraphQL on in one domain",
                            other, domain, name, name, Character.toLowerCase(name.charAt(0)) + name.substring(1)));
                } else {
                    servedBy.put(name, domain);
                }
            }
        }
        return out;
    }

    /**
     * The properties file with the path, where a domain names one; removed
     * when none does any more - only a file this wrote.
     */
    public static void writeProperties(File root, List<ECoreModel> models) throws IOException {
        String path = null;
        for (ECoreModel m : models) {
            if (enabled(m) && path(m) != null) path = path(m);
        }
        File file = new File(root, PROPERTIES);
        if (path == null) {
            if (file.isFile() && ours(file)) Files.delete(file.toPath());
            return;
        }
        String text = HEADER + "\nspring.graphql.path=" + path + "\n";
        if (file.isFile() && text.equals(new String(Files.readAllBytes(file.toPath()), StandardCharsets.UTF_8))) return;
        Files.createDirectories(file.getParentFile().toPath());
        Files.write(file.toPath(), text.getBytes(StandardCharsets.UTF_8));
    }

    private static boolean ours(File file) throws IOException {
        List<String> lines = Files.readAllLines(file.toPath(), StandardCharsets.UTF_8);
        return !lines.isEmpty() && HEADER.equals(lines.get(0));
    }
}
